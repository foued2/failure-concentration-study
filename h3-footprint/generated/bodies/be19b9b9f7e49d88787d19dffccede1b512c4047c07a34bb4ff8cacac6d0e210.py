def solve(n, edges, s, t):
    adj = [[] for _ in range(n)]
    for u, v, w in edges:
        adj[u].append((v, w))
    INF = float('inf')
    dist = [INF] * n
    dist[s] = 0
    frontier = [(0, s)]
    while frontier:
        d, u = frontier.pop(0)
        if d > dist[u]:
            continue
        if u == t:
            return d
        for v, w in adj[u]:
            nd = d + w
            if nd < dist[v]:
                dist[v] = nd
                insort(frontier, (nd, v))
    return -1 if dist[t] == INF else int(dist[t])
